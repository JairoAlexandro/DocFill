export type Lang = 'es' | 'en';
export const LANGS: { id: Lang; name: string }[] = [
  { id: 'es', name: 'Español' },
  { id: 'en', name: 'English' },
];
const DICTS: Record<Lang, Record<Key, string>> = { es, en };

export type TFunction = (key: string, vars?: Record<string, string | number>) => string;

interface I18n {
  lang: Lang;
  locale: string;
  setLang: (l: Lang) => void;
  /** Traduce una clave. Si no existe, devuelve el texto tal cual (útil para mensajes de error). */
  t: TFunction;
}

const STORAGE_KEY = 'docfill.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'es' || saved === 'en') return saved;
  } catch {
    /* sin almacenamiento: se usa el idioma del sistema */
  }
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : navigator.language ? 'en' : 'es';
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* se mantiene solo en esta sesión */
    }
  }, []);

  const t = useCallback<TFunction>(
    (key, vars) => {
      let s: string = (DICTS[lang] as Record<string, string>)[key] ?? (es as Record<string, string>)[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, locale: lang === 'es' ? 'es-ES' : 'en-GB', setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const c = useContext(Ctx);
  if (!c) throw new Error('useI18n fuera de I18nProvider');
  return c;
}
